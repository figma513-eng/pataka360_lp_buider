export function resolveSocialMetrics(content?: {
  socialSize?: 'sm' | 'md' | 'lg';
  socialIconSize?: number;
  socialGap?: number;
  socialStyle?: 'filled' | 'outline' | 'minimal';
}) {
  const legacyBox =
    content?.socialSize === 'sm' ? 32 : content?.socialSize === 'lg' ? 48 : 40;
  const boxSize = content?.socialIconSize ?? legacyBox;
  const iconSize =
    content?.socialStyle === 'minimal'
      ? Math.round(boxSize * 0.65)
      : Math.round(boxSize * 0.5);
  const gap = content?.socialGap ?? 10;
  return { boxSize, iconSize, gap };
}
